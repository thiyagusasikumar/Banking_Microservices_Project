-- Run manually in the account-service PostgreSQL database.
-- Matches the current Account entity: Long IDs, two decimal places,
-- LocalDateTime timestamps, and the current AccountStatus enum values.
-- IF NOT EXISTS does not change constraints on an existing accounts table.
CREATE TABLE accounts (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          customer_id BIGINT NOT NULL,
                          account_number VARCHAR(34) NOT NULL UNIQUE,
                          account_type VARCHAR(20) NOT NULL,
                          balance NUMERIC(19,2) NOT NULL DEFAULT 0.00,
                          currency VARCHAR(3) NOT NULL,
                          account_status VARCHAR(30) NOT NULL,
                          version BIGINT NOT NULL DEFAULT 0,
                          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                          updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_account_type
                              CHECK (account_type IN ('SAVINGS', 'CURRENT')),

                          CONSTRAINT chk_balance
                              CHECK (balance >= 0),

                          CONSTRAINT chk_account_status
                              CHECK (account_status IN (
                                                        'PENDING_ACTIVATION',
                                                        'ACTIVE',
                                                        'FROZEN',
                                                        'RESTRICTED',
                                                        'CLOSURE_PENDING',
                                                        'CLOSED'
                                  ))
);
